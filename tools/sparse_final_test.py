#!/usr/bin/env python3
"""Replay sealed programs against separate matrix files without model access.

Selection JSON: {programs:[{kernel,path,sha256,label}]}.
Matrix JSON: {matrices:[{kernel,path,sha256,id,values:'original',partition:'final_test'}]}.
Paths are relative to their manifest. Freeze both manifests before evaluation.
This tool never selects programs, edits computation, or invokes a model.
"""
import argparse,json,os,shutil,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'code_translation'));sys.path.insert(0,str(ROOT/'tools'))
from benchmark_csl import benchmark_translated_compute_file
from sparse_study import base_environment,sha,save
import sparse_inputs as si

SPMV_INPUTS='''# External final-test matrix; host ABI and numerical tolerance unchanged.
import sparse_inputs as si
SEED = si.resolve_eval_seed(7, where=os.path.dirname(__file__))
print(f"eval_seed = {SEED}")
csr, entry = si.load_manifest_matrix(os.path.join(os.path.dirname(__file__), 'data/manifest.json'), SEED)
assert csr.m <= ncols
pad = si.csr_pad(csr, nrows, max_nnz)
row_ptr, col_idx, val = pad['row_ptr'], pad['col'], pad['val']
x = np.random.default_rng([SEED, 1]).uniform(-1, 1, ncols).astype(np.float32)
y_ref = np.zeros(nrows, dtype=np.float32)
y_ref[:csr.n] = csr.matvec(x[:csr.m]).astype(np.float32)
print(f"matrix = {entry['id']} n={csr.n} m={csr.m} nnz={csr.nnz}")
'''

def main():
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('study','selection','matrices','out'):p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--sdk-root',type=Path,default=Path.home()/'cs_sdk');a=p.parse_args()
    manifest=json.loads((a.study/'inputs/manifest.json').read_text())
    selected=json.loads(a.selection.read_text())['programs'];matrices=json.loads(a.matrices.read_text())['matrices']
    os.environ.update(base_environment(manifest['protocol'],a.sdk_root))
    os.environ.update(XKERNEL_DATA_PARTITION='final_test',XKERNEL_HELDOUT_EVAL='0',XKERNEL_PROFILE_TRAIN_REPLAY='0',XKERNEL_IR_CAPTURE='0')
    for key in ('OPENAI_API_KEY','DEEPSEEK_API_KEY','XKERNEL_CALL_ARCHIVE'):os.environ.pop(key,None)
    seal=dict(selection_sha256=sha(a.selection),matrices_sha256=sha(a.matrices),framework_commit=manifest['source_commit'])
    seal_path=a.out/'seal.json'
    if seal_path.exists() and json.loads(seal_path.read_text())!=seal:raise RuntimeError('Selection/test manifest changed after final-test evaluation began')
    save(seal_path,seal)
    # Reject any final matrix already used by a development input bundle.
    def pattern(path):
        import hashlib
        c=si.read_mtx(path)
        h=hashlib.sha256(str((c.n,c.m)).encode())
        h.update(c.row_ptr.astype('<i8').tobytes());h.update(c.col.astype('<i8').tobytes())
        return h.hexdigest()
    development={v for k,v in manifest['sha256'].items() if k.endswith('.mtx')}
    development_patterns={pattern(a.study/'inputs'/k) for k in manifest['sha256'] if k.endswith('.mtx')}
    # The single-PE SpMV development inputs are generated by its host rather
    # than stored as MTX files. Include their exact patterns in the firewall.
    import tempfile,yaml
    from sparse_cuda_baselines import host_inputs
    from scipy.sparse import csr_matrix
    generated=Path(manifest['tasks']['SpMV-CSR']['reference_csl_dir'])
    params=next(s['params'] for s in yaml.safe_load((generated.parent/'spec.yaml').read_text())['sizes'] if s['name']=='small')
    with tempfile.TemporaryDirectory() as d:
        for seed in (7,101,202,303):
            values,_=host_inputs(generated,params,seed)
            path=Path(d)/'generated.mtx';si.write_mtx(path,si.from_scipy(csr_matrix(values['A'])))
            development_patterns.add(pattern(path))
    for matrix in matrices:
        path=a.matrices.parent/matrix['path']
        if matrix.get('partition')!='final_test' or sha(path)!=matrix['sha256']:raise RuntimeError('Invalid final-test input')
        if matrix['sha256'] in development:raise RuntimeError('Final-test matrix overlaps development data')
        if pattern(path) in development_patterns:raise RuntimeError('Final-test sparsity pattern overlaps development data')
        if matrix.get('values')!='original':raise RuntimeError('Matrix file must store the actual frozen evaluation values')
    results=[]
    for item in selected:
        source=a.selection.parent/item['path'];name=item['kernel']
        if sha(source)!=item['sha256']:raise RuntimeError('Selected source changed: '+str(source))
        spec=manifest['tasks'][name]
        for index,matrix in enumerate(m for m in matrices if m['kernel']==name):
            dest=a.out/name/item['label']/str(index)
            if (dest/'result.json').exists():results.append(json.loads((dest/'result.json').read_text()));continue
            ref=dest/'reference/CSL';ref.parent.mkdir(parents=True)
            shutil.copytree(spec['reference_csl_dir'],ref)
            shutil.copy2(Path(spec['reference_csl_dir']).parent/'spec.yaml',ref.parent/'spec.yaml')
            data=ref/'data'
            if data.exists():shutil.rmtree(data)
            data.mkdir()
            if name=='SpMV-CSR':
                host=(ref/'run.py').read_text();start=host.index('# --- Build a random sparse matrix');end=host.index('# --- Run on device',start)
                (ref/'run.py').write_text(host[:start]+SPMV_INPUTS+'\n'+host[end:])
            shutil.copy2(a.matrices.parent/matrix['path'],data/'final.mtx')
            csr=si.read_mtx(data/'final.mtx')
            entry=dict(id=matrix['id'],file='final.mtx',sha256=matrix['sha256'],n=csr.n,m=csr.m,nnz=csr.nnz)
            save(data/'manifest.json',dict(schema=1,train_seed=7,values='original',matrices=[entry]))
            b=benchmark_translated_compute_file(str(source),str(ref),spec['target_relpath'],str(dest/'replay'),str(a.sdk_root),commands_script=spec['commands_script'],keep_staged_bundle=True,num_runs=3,heldout_eval=False)
            result=dict(kernel=name,label=item['label'],source_sha256=item['sha256'],matrix_id=matrix['id'],matrix_sha256=matrix['sha256'],partition='final_test',correct=b['status']=='pass' and b['success_marker'],cycles=b.get('cycles_send'),cycles_runs=b.get('cycles_send_runs'),benchmark=b)
            save(dest/'result.json',result);results.append(result);save(a.out/'summary.json',results)
            print(name,item['label'],matrix['id'],result['correct'],result['cycles'],flush=True)

if __name__=='__main__':main()
